const TABLES: Record<Locale, Record<string, string>> = { en: EN, tr: TR };

export type EmailTextKey = Key | "digestSubject" | "digestBody" | "fwdDigestTitle" | "assignSubject" | "assignBody" | "notifyDigestSubject" | "notifyDigestIntro";

/** A sentence in the given language; {name} placeholders are filled from vars, "<key>_one/_other" chosen by vars.count. */
export function emailText(locale: Locale, key: EmailTextKey, vars: Record<string, string | number> = {}): string {
  const table = TABLES[locale];
  let template = table[key];
  if (template === undefined && typeof vars.count === "number") {
    template = table[`${key}_${new Intl.PluralRules(locale).select(vars.count)}`] ?? table[`${key}_other`];
  }
  template ??= EN[key as Key] ?? key;
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** 1.0.2: what to do about an alert of this kind, or null for a kind without advice. */
export function alertHint(locale: Locale, kind: string): string | null {
  return TABLES[locale][`alertHint_${kind}`] ?? null;
}

/** A Human Review reason code in words; unknown codes are shown as they are ("some_reason" → "some reason"). */
export function reviewReason(locale: Locale, reason: string): string {
  const text = TABLES[locale][`reason_${reason}`];
  return text ?? reason.replace(/_/g, " ");
}
